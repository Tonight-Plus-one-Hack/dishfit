// Builds the real-data D1 seed from the merged pipeline export: every per-Kiez file in
// apps/web/src/data/seed/pipeline/kiez/*.json (written by `npm run scan` in pipeline/, merged via PRs).
// Output is plain SQL for `wrangler d1 execute DB --file worker/seed/real.sql` (local or --remote).
// The merge rules match apps/web/src/data/seed/pipeline.ts: files in name order, a place that appears
// twice (same id, Google place id or OSM element) is kept once, from the first file.
// Ids stay the web seed's ids, so the API and the bundled app agree on restaurant and dish ids.
// Re-running the seed updates changed pipeline rows and leaves other rows alone.
// Every dish carries its class and the healthy flag (packages/contract/src/dish-class.ts); unhealthy dishes are
// stored but never served, and a restaurant with fewer than two healthy dishes is stored unpublished.
//
// Usage: node worker/scripts/build-seed.ts [--out worker/seed/real.sql]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  HEALTHY_RULES,
  isHealthy,
  stripMenuNumber,
  unpackDishClass,
  type CompactDishClass,
  type DishClass,
} from "../../packages/contract/src/dish-class.ts";

interface SeedDish {
  id: string;
  name: string;
  description: string;
  price: number | null;
  category: string;
  n: number[];
  confidence: "high" | "medium" | "low";
  source: "ai" | "official";
  method: number;
  ingredients: [number, number][];
  healthScore: number;
  image: string | null;
  /** [course, dishType, cuisine, flags, confidence] from the pipeline classifier. */
  c?: CompactDishClass;
  sourceUrl?: string;
}

interface SeedRestaurant {
  id: string;
  placeId: string | null;
  osmId: string | null;
  name: string;
  address: string;
  lat: number;
  lng: number;
  openingHours: { periods: unknown[] } | null;
  website: string | null;
  menu: { url: string; fetchedAt: string; kind: string };
  dishes: SeedDish[];
}

interface WebSeed {
  v: 1;
  generatedAt: string;
  methods: string[];
  ingredientNames: string[];
  restaurants: SeedRestaurant[];
}

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const kiezDir = join(repo, "apps/web/src/data/seed/pipeline/kiez");
const imageDir = join(repo, "apps/web/src/data/seed/pipeline/images");
const logos = JSON.parse(readFileSync(join(kiezDir, "../logos.json"), "utf8")) as Record<string, { url: string }>;
const outArg = process.argv.indexOf("--out");
const out = resolve(outArg > 0 ? process.argv[outArg + 1]! : join(repo, "worker/seed/real.sql"));

type Value = string | number | null;

function lit(v: Value): string {
  if (v === null) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  return `'${v.replace(/'/g, "''")}'`;
}

function upsert(table: string, rows: Record<string, Value>[]): string[] {
  if (!rows.length) return [];
  const columns = Object.keys(rows[0]!);
  const mutable = columns.filter((name) => name !== "id" && name !== "created_at");
  const changed = mutable.filter((name) => name !== "updated_at").map((name) => name === "published_at"
    ? `(excluded.published_at IS NULL) != (${table}.published_at IS NULL)`
    : `excluded.${name} IS NOT ${table}.${name}`).join(" OR ");
  const updates = mutable.map((name) => `${name} = excluded.${name}`).join(", ");
  const head = `INSERT INTO ${table} (${columns.join(", ")}) VALUES `;
  const tail = ` ON CONFLICT (id) DO UPDATE SET ${updates} WHERE ${changed};`;
  const batches: string[] = [];
  let values: string[] = [];
  let bytes = Buffer.byteLength(head + tail);
  for (const row of rows) {
    const tuple = `(${columns.map((name) => lit(row[name] ?? null)).join(", ")})`;
    const length = Buffer.byteLength(tuple) + 2;
    if (values.length && bytes + length > 90_000) {
      batches.push(head + values.join(",\n") + tail);
      values = [];
      bytes = Buffer.byteLength(head + tail);
    }
    bytes += length;
    values.push(tuple);
  }
  batches.push(head + values.join(",\n") + tail);
  return batches;
}

/** value, min, max with min <= value <= max (the dishes CHECK constraints). */
function range(n: number[], i: number): [number, number, number] {
  const [v, min, max] = [n[i * 3]!, n[i * 3 + 1]!, n[i * 3 + 2]!];
  return [v, Math.min(min, v), Math.max(max, v)];
}

function menuKind(url: string): string {
  const path = url.toLowerCase().split(/[?#]/)[0]!;
  if (path.endsWith(".pdf")) return "website_pdf";
  if (/\.(jpe?g|png|webp|gif|avif)$/.test(path)) return "website_image";
  return "website_html";
}

const images = new Map(
  readdirSync(imageDir).map((file) => [file.replace(/\.[a-z]+$/, ""), file] as const),
);

const statements: string[] = [
  "-- Generated by worker/scripts/build-seed.ts from apps/web/src/data/seed/pipeline/kiez/*.json. Do not edit.",
  "-- Pipeline rows have osm-* restaurant ids. Only the pipeline's website menu is managed here.",
];
const seen = new Set<string>();
const dishIds = new Set<string>();
const restaurantIds: string[] = [];
const placeOwners: Record<string, string> = {};
const logoUrls: Record<string, string | null> = {};
let restaurantCount = 0;
let dishCount = 0;
let imageCount = 0;
let healthyCount = 0;
let hiddenRestaurants = 0;

const bit = (b: boolean) => (b ? 1 : 0);

/** dishes.course ... dishes.healthy (worker/migrations/0043_dish_class.sql); NULL until the dish is classified. */
function classColumns(c: DishClass | null, healthy: boolean): Record<string, Value> {
  return {
    course: c?.course ?? null,
    dish_type: c?.dishType ?? null,
    cuisine: c?.cuisine ?? null,
    is_vegan: c ? bit(c.vegan) : null,
    is_vegetarian: c ? bit(c.vegetarian) : null,
    is_gluten_free: c ? bit(c.glutenFree) : null,
    is_full_meal: c ? bit(c.isFullMeal) : null,
    class_confidence: c?.confidence ?? null,
    healthy: c ? bit(healthy) : null,
  };
}

for (const file of readdirSync(kiezDir).filter((f) => f.endsWith(".json")).toSorted()) {
  const kiez = basename(file, ".json");
  const seed = JSON.parse(readFileSync(join(kiezDir, file), "utf8")) as WebSeed;
  const generatedAt = Date.parse(seed.generatedAt);
  for (const r of seed.restaurants) {
    if (!r.id.startsWith("osm-")) throw new Error(`${file}: restaurant id ${r.id} does not start with osm-`);
    const keys = [`id:${r.id}`, r.placeId ? `place:${r.placeId}` : "", r.osmId ? `osm:${r.osmId}` : ""].filter(Boolean);
    if (keys.some((k) => seen.has(k))) continue;
    keys.forEach((k) => seen.add(k));
    restaurantIds.push(r.id);
    if (r.placeId) placeOwners[r.placeId] = r.id;
    logoUrls[r.id] = logos[r.id]?.url ?? null;
    restaurantCount++;
    const healthyOf = (d: SeedDish) => isHealthy({ cls: d.c ? unpackDishClass(d.c) : null, kcal: d.n[0]!, proteinG: d.n[3]! });
    const listed = !!r.placeId && r.dishes.filter(healthyOf).length >= HEALTHY_RULES.minDishesPerRestaurant;
    if (!listed) hiddenRestaurants++;
    statements.push(
      ...upsert("restaurants", [{
        id: r.id,
        google_place_id: r.placeId,
        name: r.name,
        kiez,
        lat: r.lat,
        lng: r.lng,
        address: r.address || null,
        website_url: r.website,
        opening_hours: r.openingHours ? JSON.stringify({ periods: r.openingHours.periods }) : null,
        published_at: listed ? generatedAt : null,
        created_at: generatedAt,
        updated_at: generatedAt,
      }]),
    );
    const menuId = `${r.id}-menu`;
    const fetchedAt = Date.parse(r.menu.fetchedAt);
    statements.push(
      ...upsert("menu_sources", [{
        id: menuId,
        restaurant_id: r.id,
        kind: menuKind(r.menu.url),
        url: r.menu.url,
        content_sha256: null,
        fetched_at: fetchedAt,
        created_at: fetchedAt,
      }]),
    );
    const rows: Record<string, Value>[] = [];
    for (const d of r.dishes) {
      if (dishIds.has(d.id)) continue;
      dishIds.add(d.id);
      dishCount++;
      const [kcal, kcalMin, kcalMax] = range(d.n, 0);
      const [protein, proteinMin, proteinMax] = range(d.n, 1);
      const [carbs, carbsMin, carbsMax] = range(d.n, 2);
      const [fat, fatMin, fatMax] = range(d.n, 3);
      const imageFile = d.image ? images.get(d.image) : undefined;
      const healthy = healthyOf(d);
      if (healthy) healthyCount++;
      if (imageFile) imageCount++;
      rows.push({
          id: d.id,
          restaurant_id: r.id,
          menu_source_id: menuId,
          menu_item_source_url: d.sourceUrl ?? null,
          name: stripMenuNumber(d.name),
          description: d.description || null,
          category: d.category || null,
          price_cents: d.price === null ? null : Math.round(d.price * 100),
          kcal,
          kcal_min: kcalMin,
          kcal_max: kcalMax,
          protein_g: protein,
          protein_g_min: proteinMin,
          protein_g_max: proteinMax,
          carbs_g: carbs,
          carbs_g_min: carbsMin,
          carbs_g_max: carbsMax,
          fat_g: fat,
          fat_g_min: fatMin,
          fat_g_max: fatMax,
          nutrition_source: d.source,
          confidence: d.confidence,
          method_note: seed.methods[d.method] ?? null,
          ingredients: JSON.stringify(d.ingredients.map(([name, grams]) => ({ name: seed.ingredientNames[name], grams }))),
          estimated_at: fetchedAt,
          health_score: d.healthScore,
          // Same file the web build bundles; upload to R2 under this key (docs/deploy.md) for /api/images/ai/:file.
          ai_image_key: imageFile ? `ai/${imageFile}` : null,
          published_at: d.c ? generatedAt : null,
          created_at: generatedAt,
          updated_at: generatedAt,
          ...classColumns(d.c ? unpackDishClass(d.c) : null, healthy),
      });
    }
    statements.push(...upsert("dishes", rows));
    statements.push(`DELETE FROM dishes WHERE restaurant_id = ${lit(r.id)} AND menu_source_id = ${lit(menuId)} AND id NOT IN (SELECT value FROM json_each(${lit(JSON.stringify(rows.map((row) => row.id)))}));`);
  }
}

// A corrected match can move a Place ID between OSM IDs; free it before any inserts or updates.
statements.splice(2, 0, `UPDATE restaurants SET google_place_id = NULL WHERE id LIKE 'osm-%' AND EXISTS (
  SELECT 1 FROM json_each(${lit(JSON.stringify(placeOwners))}) AS owner
   WHERE owner.key = restaurants.google_place_id AND owner.value <> restaurants.id);`);
// Updating the unindexed logo column separately avoids rewriting restaurant indexes on a logo-only release.
statements.push(`UPDATE restaurants SET logo_url = logo.value
  FROM json_each(${lit(JSON.stringify(logoUrls))}) AS logo
 WHERE restaurants.id = logo.key AND restaurants.logo_url IS NOT logo.value;`);
// A place removed from the seeds is taken out of the public catalog. Keep the restaurant and its community history.
statements.push(`UPDATE restaurants SET published_at = NULL WHERE id LIKE 'osm-%' AND published_at IS NOT NULL AND id NOT IN (SELECT value FROM json_each(${lit(JSON.stringify(restaurantIds))}));`);

writeFileSync(out, `${statements.join("\n")}\n`);
console.log(
  `${out}: ${restaurantCount} restaurants (${hiddenRestaurants} unpublished, under ${HEALTHY_RULES.minDishesPerRestaurant} healthy dishes), ${dishCount} dishes (${healthyCount} healthy), ${imageCount} with KI-Bild`,
);
