#!/usr/bin/env node
// Refreshes this film's brand inputs from the brand kit in ../ (brand/assets, brand/fonts),
// which stays the single source of truth. HyperFrames serves only files inside this project,
// so the film keeps committed copies under assets/; render.mjs runs this first so they never drift.
//
//   node scripts/sync-brand.mjs            write the copies, list what changed
//   node scripts/sync-brand.mjs --check    exit 1 if any copy differs from the brand kit
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const project = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const brand = resolve(project, "..");

// The lockup draws the wordmark as one outlined path placed with translate(x y).
// Its bounding box becomes the wordmark's viewBox, so the film can size it on its own.
function extractWordmark(lockupSvg) {
  const match = lockupSvg.match(/<path transform="translate\(([\d.]+) ([\d.]+)\)" d="([^"]+)"/);
  if (!match) throw new Error("logo-primary.svg: no translated wordmark path found");
  const [, tx, ty, d] = match;
  const tokens = d.match(/[A-Za-z]|-?\d*\.?\d+(?:e-?\d+)?/g);
  const xs = [];
  const ys = [];
  let command = null;
  let x = 0;
  let y = 0;
  for (let i = 0; i < tokens.length; ) {
    if (/[A-Za-z]/.test(tokens[i])) command = tokens[i++];
    if (command === "Z") continue;
    const n = (k) => Number(tokens[i + k]);
    if (command === "M" || command === "L") [x, y, i] = [n(0), n(1), i + 2];
    else if (command === "H") [x, i] = [n(0), i + 1];
    else if (command === "V") [y, i] = [n(0), i + 1];
    else if (command === "Q") {
      xs.push(n(0));
      ys.push(n(1));
      [x, y, i] = [n(2), n(3), i + 4];
    } else throw new Error(`logo-primary.svg: unsupported path command ${command}; extend extractWordmark`);
    xs.push(x);
    ys.push(y);
  }
  const round = (v) => Number(v.toFixed(3));
  const minX = round(Math.min(...xs) + Number(tx));
  const minY = round(Math.min(...ys) + Number(ty));
  const width = round(Math.max(...xs) - Math.min(...xs));
  const height = round(Math.max(...ys) - Math.min(...ys));
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${minX} ${minY} ${width} ${height}" role="img" aria-label="Plus One wordmark">`,
    `  <!-- Generated by scripts/sync-brand.mjs from brand/assets/logo-primary.svg. Do not edit. -->`,
    `  <path transform="translate(${tx} ${ty})" fill="#1c2024" d="${d}"/>`,
    `</svg>`,
    ``,
  ].join("\n");
}

const outputs = [
  ["assets/logo.svg", () => readFileSync(join(brand, "assets/symbol.svg"))],
  ["assets/lockup.svg", () => readFileSync(join(brand, "assets/logo-primary.svg"))],
  ["assets/wordmark.svg", () => extractWordmark(readFileSync(join(brand, "assets/logo-primary.svg"), "utf8"))],
  ["assets/fonts/source-serif-4.woff2", () => readFileSync(join(brand, "fonts/source-serif-4.woff2"))],
  ["assets/fonts/geist-mono.woff2", () => readFileSync(join(brand, "fonts/geist-mono.woff2"))],
  ["assets/fonts/OFL-Source-Serif-4.txt", () => readFileSync(join(brand, "fonts/OFL-Source-Serif-4.txt"))],
  ["assets/fonts/OFL-Geist-Mono.txt", () => readFileSync(join(brand, "fonts/OFL-Geist-Mono.txt"))],
];

const checkOnly = process.argv.includes("--check");
const drifted = [];
for (const [target, build] of outputs) {
  const path = join(project, target);
  const next = Buffer.from(build());
  const current = existsSync(path) ? readFileSync(path) : null;
  if (current && current.equals(next)) continue;
  drifted.push(relative(project, path));
  if (!checkOnly) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, next);
  }
}
if (checkOnly && drifted.length) {
  console.error(`Out of sync with the brand kit: ${drifted.join(", ")}. Run node scripts/sync-brand.mjs`);
  process.exit(1);
}
console.log(drifted.length ? `${checkOnly ? "Differs" : "Updated"}: ${drifted.join(", ")}` : "Brand inputs in sync");
