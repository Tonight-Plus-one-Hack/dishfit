#!/usr/bin/env python3
"""Build submission/slides.html from slides.src.html and the brand kit.

Inlines the brand fonts, artwork and logo so slides.html is one self-contained
file that works offline and from any folder. Re-run after editing the source or
after the brand kit changes:

    python3 submission/build-slides.py
"""

import base64
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BRAND = HERE.parent / "brand"
SRC = HERE / "slides.src.html"
OUT = HERE / "slides.html"

MIME = {".woff2": "font/woff2", ".webp": "image/webp", ".png": "image/png", ".svg": "image/svg+xml"}
BANNER = "<!-- Generated by submission/build-slides.py from slides.src.html and brand/. Edit the source, then rebuild. -->\n"


def data_uri(path: Path) -> str:
    return f"data:{MIME[path.suffix]};base64,{base64.b64encode(path.read_bytes()).decode('ascii')}"


def logo_svg() -> str:
    svg = (BRAND / "assets" / "logo-primary.svg").read_text(encoding="utf-8").strip()
    svg = re.sub(r"<\?xml[^>]*\?>\s*", "", svg)
    svg = svg.replace('aria-label="Plus One Primary logo"', 'aria-label="Plus One"', 1)
    return svg.replace("<svg ", '<svg class="logo" ', 1)


def main() -> int:
    html = SRC.read_text(encoding="utf-8")
    html = re.sub(r"\{\{FONT:([\w.-]+)\}\}", lambda m: data_uri(BRAND / "fonts" / m.group(1)), html)
    html = re.sub(r"\{\{IMG:([\w.-]+)\}\}", lambda m: data_uri(BRAND / "assets" / m.group(1)), html)
    html = html.replace("{{LOGO}}", logo_svg())
    left = re.findall(r"\{\{[^}]*\}\}", html)
    if left:
        print(f"unresolved placeholders: {left}", file=sys.stderr)
        return 1
    html = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER, 1)
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE.parent)} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
