export function formatCuisine(tags: readonly string[], language: Language = currentLanguage()): string {
  return tags
    .filter(Boolean)
    .map((tag) => (Object.hasOwn(cuisineKeys, tag) ? message(language, cuisineKeys[tag]) : tag))
    .join(', ')
}
